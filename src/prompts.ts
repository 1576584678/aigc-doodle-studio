/** 火柴人专用姿态块：短，且不套用动物 C3 分区坐标，不改第 3~5 条既有约束。 */
export const STICKMAN_POSE_BLOCK = `【火柴人姿态硬约束（不得覆盖以上任何输出格式规范）】
描述含「跑/跳/挥手」时：四肢至少 3 个不同角度、每条肢体至少 2 段折线体现关节、躯干有可见倾角；可在身后加 2~3 条水平短速度线（长 40~60、间距 20~30）。严禁四肢平行且垂直向下。保持第 3~5 条既有约束（圆圈头部、直线躯干四肢、姿态符合描述）不变；不得套用动物构图分区坐标。`

/** 追加到 8 条硬性规范之后的风格约束，绝不覆盖任何白名单/输出格式要求。 */
export const STYLE_INSTRUCTIONS: Record<StyleKey, string> = {
  minimal:
    '风格约束：极简线稿。极简＝删除装饰性线条（花纹、阴影、重复排线），不是删除辨识特征；构图硬约束中的每个辨识特征都必须保留并简化为最少必要笔画，每项至少 1 笔、不得省略；画面干净、不加背景。',
  cute:
    '风格约束：圆润可爱。轮廓改用弧线（Q/C 曲线）、转角圆润，头身比例可略夸张（头偏大）；但辨识特征清单不得删减，禁止用一个圆或椭圆代表整个主体。',
  coloring:
    '风格约束：涂色线稿（打印后可涂色）。每个辨识特征各是一条独立闭合路径以便分区涂色，轮廓之间不重叠、留 2~4px 间隙；所有图元 fill="none"、不做色块填充；stroke-width 至少 4（建议 5）保证打印清晰；禁止用单一大椭圆包住全部特征。'
}

/**
 * 拼接顺序：8 条硬规范（base）→ 构图/姿态块（居中）→ 【追加风格约束】（最末）。
 * doodle 与 stickman 走不同构图块；风格约束仍居末，绝不覆盖前面的输出格式与白名单要求。
 */
export function buildSystemPrompt(base: string, style: StyleKey): string {
  const block = STYLE_INSTRUCTIONS[style] ?? STYLE_INSTRUCTIONS.minimal
  const composition = base === DOODLE_PROMPT ? DOODLE_COMPOSITION : STICKMAN_POSE_BLOCK
  return (
    `${base}\n\n${composition}\n\n` +
    '【追加风格约束（不得覆盖以上任何硬性规范，输出格式与白名单要求仍然生效）】\n' +
    block
  )
}
