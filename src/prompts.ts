/**
 * 简笔画构图块（FR-09 的「追加」内容）。
 * 只在心里做类别判断，不要求模型输出任何额外文字或标签。
 * 所有部件都指「该主体自身真实的结构」，不再套用固定解剖模板。
 */
export const DOODLE_COMPOSITION = `【构图与辨识度（补充以上规则，与以上每一条同时生效）】
第一步 · 先在心里判断主体类别，不要输出判断过程：
A 生物（人/动物）｜B 物品｜C 场景｜D 抽象或其他。
描述含多个主体时只画最主要的一个；描述过短（如只写「猫」）按最常见形象补全。

第二步 · 按类别列出 3~5 个不可替代的辨识特征，逐一画出，每项至少 1 笔：
· A 生物：头 + 躯干 + 该物种真实数量与形态的肢体 + 最独特的 1~2 个部位（猫＝三角立耳＋胡须，鸟＝喙＋翅＋尾，狗＝口鼻前突＋垂耳）。只有四足动物才画四条腿和尾巴；人物画两臂两腿；禁止给主体强加不属于它的部件。
· B 物品：主体轮廓＋1~2 个功能部件＋1 个状态细节（咖啡＝杯身＋杯把＋热气；伞＝伞面＋伞柄＋雨滴）。禁止只画一个外框。
· C 场景：先画一条 y≈280~320 的地平线，2~3 个元素分前后层次、近大远小，禁止全部同尺寸同水平线。
· D 抽象：先化为一个可画的具体主体，再按 A 或 B 处理。

第三步 · 通用画面规则（所有类别都适用）：
G1 主体居中，外接框占画面 60~80%（约 240~320px）；所有笔画留在 x/y ∈ [40,360] 安全区。
G2 禁止用一个闭合圆或椭圆代表整个主体；各部件独立可辨，相邻部件间有可见连接线，不得悬空。
G3 姿态靠角度差表达：描述含「跑/奔/跳/飞/挥手」时，四肢≥3 个不同角度、参与动作的肢体≥2 段折线体现关节、躯干倾斜 10~20°，可在身后加 2~3 条水平短速度线（长 40~60、间距 20~30）；严禁四肢平行且垂直向下。静态姿态保持自然站立，不要强行倾斜或加速度线。
G4 五官仅生物可加，只用 2 点眼＋1 笔嘴；柔和色块≤3 种且仅作点缀，不用红色小点充当五官。
G5 「极简」＝删装饰线（花纹、阴影、重复排线），不是删辨识特征；第二步的清单每项都不得省略。
G6 线条沿用 stroke="#222" stroke-width="4"、圆角线端；不加渐变、阴影、背景。`

